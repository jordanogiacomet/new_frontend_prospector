import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const sourceCommit = "503e2f70bbf1b4b7ec0b1f68b09086ccc38fe861";
const sourceRoot = `https://raw.githubusercontent.com/kelvins/municipios-brasileiros/${sourceCommit}/json`;
const outputPath = resolve(
  process.cwd(),
  "src/server/maps/data/brazilian-municipality-centroids.ts",
);

function normalizeName(value) {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

async function loadJson(name) {
  const response = await fetch(`${sourceRoot}/${name}.json`);
  if (!response.ok) {
    throw new Error(`Failed to download ${name}: HTTP ${response.status}`);
  }

  return response.json();
}

const [states, municipalities] = await Promise.all([
  loadJson("estados"),
  loadJson("municipios"),
]);

if (!Array.isArray(states) || !Array.isArray(municipalities)) {
  throw new Error("Unexpected municipality source shape.");
}

const stateByCode = new Map(
  states.map((state) => [state.codigo_uf, state.uf]),
);
const entries = new Map();

for (const municipality of municipalities) {
  const uf = stateByCode.get(municipality.codigo_uf);
  const latitude = municipality.latitude;
  const longitude = municipality.longitude;

  if (
    typeof uf !== "string" ||
    !/^[A-Z]{2}$/.test(uf) ||
    typeof municipality.nome !== "string" ||
    typeof latitude !== "number" ||
    !Number.isFinite(latitude) ||
    latitude < -90 ||
    latitude > 90 ||
    typeof longitude !== "number" ||
    !Number.isFinite(longitude) ||
    longitude < -180 ||
    longitude > 180
  ) {
    throw new Error("Unexpected municipality record.");
  }

  const key = `${uf.toLowerCase()}|${normalizeName(municipality.nome)}`;
  if (entries.has(key)) {
    throw new Error(`Duplicate normalized municipality key: ${key}`);
  }

  entries.set(key, [latitude, longitude]);
}

if (entries.size !== 5_571) {
  throw new Error(`Expected 5571 municipalities, received ${entries.size}.`);
}

const lines = [
  "// Generated by scripts/generate-brazilian-municipality-centroids.mjs.",
  `// Source: kelvins/municipios-brasileiros@${sourceCommit} (MIT).`,
  "// Do not edit this file manually.",
  "export const brazilianMunicipalityCentroids = {",
  ...[...entries.entries()]
    .sort(([left], [right]) => left.localeCompare(right, "pt-BR"))
    .map(
      ([key, [latitude, longitude]]) =>
        `  ${JSON.stringify(key)}: [${latitude}, ${longitude}],`,
    ),
  "} as const satisfies Readonly<",
  "  Record<string, readonly [number, number]>",
  ">;",
  "",
];

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, lines.join("\n"), "utf8");
process.stdout.write(`Generated ${entries.size} municipality centroids.\n`);
