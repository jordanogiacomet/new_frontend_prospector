function validateDatabaseUrl(
  rawValue: string | undefined,
  expectedDatabaseName: string,
): string {
  if (rawValue === undefined) {
    throw new Error("Both disposable PostgreSQL URLs are required.");
  }

  const url = new URL(rawValue);
  const validProtocol =
    url.protocol === "postgres:" || url.protocol === "postgresql:";

  if (
    !validProtocol ||
    url.hostname !== "localhost" ||
    (url.port !== "5432" && url.port !== "55432") ||
    decodeURIComponent(url.pathname.slice(1)) !== expectedDatabaseName ||
    url.search !== "" ||
    url.hash !== ""
  ) {
    throw new Error(
      `The disposable PostgreSQL URL must target ${expectedDatabaseName} on localhost:5432 or localhost:55432.`,
    );
  }

  return rawValue;
}

async function setupDatabases(): Promise<void> {
  mockedEnv.appDatabaseUrl = validateDatabaseUrl(
    appDatabaseUrl,
    "prospecta_t009_test",
  );
  mockedEnv.producerDatabaseUrl = validateDatabaseUrl(
    producerDatabaseUrl,
    "prospecta_t022_producer_test",
  );
  appPool = new Pool({
    connectionString: mockedEnv.appDatabaseUrl,
    application_name: "prospecta-correlated-visibility-app-test",
    max: 1,
    allowExitOnIdle: true,
  });
  producerPool = new Pool({
    connectionString: mockedEnv.producerDatabaseUrl,
    application_name: "prospecta-correlated-visibility-producer-test",
    max: 1,
    allowExitOnIdle: true,
  });

  await appPool.query(`
    CREATE SCHEMA IF NOT EXISTS prospecting_app;
    DROP TABLE IF EXISTS prospecting_app.import_submission_events;
    DROP TABLE IF EXISTS prospecting_app.import_submissions;
    CREATE TABLE prospecting_app.import_submissions (
      organization_id text NOT NULL,
      producer_import_batch_id text
    );
  `);
  await producerPool.query(`
    DROP TABLE IF EXISTS public.company_validation_runs;
    DROP TABLE IF EXISTS public.company_validations;
    CREATE TABLE public.company_validations (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      source_hash text,
      agent_version text NOT NULL,
      cnpj text NOT NULL,
      cnpj_normalizado text NOT NULL,
      nome_fantasia text,
      razao_social text,
      cidade text,
      uf text,
      cnae_descricao text,
      trust_score integer,
      priority text,
      trust_status text,
      integrity_status text NOT NULL,
      last_lead_run_id text NOT NULL,
      last_import_batch_id text,
      last_source_row integer,
      validated_at timestamptz NOT NULL
    );
    CREATE TABLE public.company_validation_runs (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      import_batch_id text,
      lead_run_id text NOT NULL,
      source_row integer,
      integrity_status text NOT NULL,
      processing_result text NOT NULL,
      cnpj_normalizado text NOT NULL,
      final_action text,
      reason text,
      run_created_at timestamptz NOT NULL,
      test_case_id text
    );
  `);

  visibilityModule = await import(
    "../../src/server/leads/lead-read-visibility"
  );
  leadListRepository = await import(
    "../../src/server/repositories/lead-list-repository"
  );
  outsideAnalysisRepository = await import(
    "../../src/server/repositories/outside-analysis-repository"
  );
}

async function resetSyntheticRows(): Promise<void> {
  await appPool?.query(`
    TRUNCATE prospecting_app.import_submissions
  `);
  await producerPool?.query(`
    TRUNCATE
      public.company_validation_runs,
      public.company_validations
    RESTART IDENTITY
  `);
}

async function insertLead(input: {
  readonly batchId: string;
  readonly cnpj: string;
  readonly sourceRow: number;
  readonly testCaseId: string | null;
  readonly processingResult?: "INSERIDO_VALIDATION" | "CRM_DECIDIU_E_SALVO";
  readonly finalAction?: string;
  readonly reason?: string | null;
}): Promise<void> {
  const leadRunId = `lr_${input.sourceRow.toString(16).padStart(8, "0")}`;
  const processingResult =
    input.processingResult ?? "INSERIDO_VALIDATION";
  const finalAction = input.finalAction ?? "PROSPECTAR";
  const reason = input.reason ?? null;

  await producerPool?.query(
    `
      INSERT INTO public.company_validation_runs (
        import_batch_id,
        lead_run_id,
        source_row,
        integrity_status,
        processing_result,
        cnpj_normalizado,
        final_action,
        reason,
        run_created_at,
        test_case_id
      )
      VALUES ($1, $2, $3, 'OK', $4, $5, $6, $7,
        '2026-07-01T12:00:00.000Z'::timestamptz, $8)
    `,
    [
      input.batchId,
      leadRunId,
      input.sourceRow,
      processingResult,
      input.cnpj,
      finalAction,
      reason,
      input.testCaseId,
    ],
  );
  await producerPool?.query(
    `
      INSERT INTO public.company_validations (
        source_hash,
        agent_version,
        cnpj,
        cnpj_normalizado,
        nome_fantasia,
        razao_social,
        cidade,
        uf,
        cnae_descricao,
        trust_score,
        priority,
        trust_status,
        integrity_status,
        last_lead_run_id,
        last_import_batch_id,
        last_source_row,
        validated_at
      )
      VALUES ($1, 'synthetic-agent-v1', $2, $2, $3, $3, 'Recife', 'PE',
        'Serviços sintéticos', 80, 'B', 'CONFIRMED', 'OK', $4, $5, $6,
        '2026-07-01T12:00:00.000Z'::timestamptz)
    `,
    [
      `synthetic-hash-${input.sourceRow}`,
      input.cnpj,
      `Empresa Sintética ${input.sourceRow}`,
      leadRunId,
      input.batchId,
      input.sourceRow,
    ],
  );
}

function enableDemo3Profile(): void {
  const mutableEnvironment = process.env as Record<
    string,
    string | undefined
  >;
  const profile = {
    NODE_ENV: "production",
    AUTH_DEV_BYPASS_ENABLED: "true",
    DEMO3_LOCAL_RUNTIME_ENABLED: "true",
    FEATURE_COMMERCIAL_ENABLED: "true",
    FEATURE_DEMO_DATA_ENABLED: "false",
    DEMO2_FULL_ACCESS_ENABLED: "false",
    DEMO2_K8S_RUNTIME_ENABLED: "false",
  };

  for (const [key, value] of Object.entries(profile)) {
    mutableEnvironment[key] = value;
  }
}

function restoreEnvironment(): void {
  const mutableEnvironment = process.env as Record<
    string,
    string | undefined
  >;

  for (const key of environmentKeys) {
    const value = originalEnvironment[key];

    if (value === undefined) {
      delete mutableEnvironment[key];
    } else {
      mutableEnvironment[key] = value;
    }
  }
}

describeIfDatabases("Demo 3 correlated lead visibility integration", () => {
  beforeAll(async () => {
    enableDemo3Profile();
    await setupDatabases();
  });

  beforeEach(async () => {
    await resetSyntheticRows();
  });

  afterAll(async () => {
    try {
      await resetSyntheticRows();
      await appPool?.query(
        "DROP TABLE IF EXISTS prospecting_app.import_submissions",
      );
      await producerPool?.query(
        "DROP TABLE IF EXISTS public.company_validation_runs",
      );
      await producerPool?.query(
        "DROP TABLE IF EXISTS public.company_validations",
      );
    } finally {
      await appPool?.end();
      await producerPool?.end();
      restoreEnvironment();
    }
  });

  it("shows production and same-organization correlated rows only", async () => {
    await insertLead({
      batchId: "synthetic-production-batch",
      cnpj: "00000000000001",
      sourceRow: 1,
      testCaseId: null,
    });
    await insertLead({
      batchId: "synthetic-same-organization-batch",
      cnpj: "00000000000002",
      sourceRow: 2,
      testCaseId: "workflow-atual",
    });
    await insertLead({
      batchId: "synthetic-other-organization-batch",
      cnpj: "00000000000003",
      sourceRow: 3,
      testCaseId: "workflow-atual",
    });
    await insertLead({
      batchId: "synthetic-uncorrelated-batch",
      cnpj: "00000000000004",
      sourceRow: 4,
      testCaseId: "workflow-atual",
    });
    await appPool?.query(
      `
        INSERT INTO prospecting_app.import_submissions (
          organization_id,
          producer_import_batch_id
        )
        VALUES
          ($1, 'synthetic-same-organization-batch'),
          ('synthetic-organization-b', 'synthetic-other-organization-batch')
      `,
      [demo3Actor.organizationId],
    );

    const visibility =
      await visibilityModule?.resolveLeadReadVisibility(demo3Actor);
    const result = await leadListRepository?.listLeads(
      { page: 1, pageSize: 20 },
      visibility,
    );

    expect(visibility).toEqual({
      includeTestRunsFromImportBatchIds: [
        "synthetic-same-organization-batch",
      ],
    });
    expect(
      result?.leads.map((lead) => lead.import_batch_id).sort(),
    ).toEqual([
      "synthetic-production-batch",
      "synthetic-same-organization-batch",
    ]);
    expect(result?.total).toBe(2);
  });

  it("shows only current CRM decisions from production and same-organization correlated batches", async () => {
    await insertLead({
      batchId: "synthetic-crm-production-batch",
      cnpj: "00000000000011",
      sourceRow: 11,
      testCaseId: null,
      processingResult: "CRM_DECIDIU_E_SALVO",
      finalAction: "NAO_ABORDAR",
      reason: "Motivo sintético de produção",
    });
    await insertLead({
      batchId: "synthetic-crm-same-organization-batch",
      cnpj: "00000000000012",
      sourceRow: 12,
      testCaseId: "workflow-atual",
      processingResult: "CRM_DECIDIU_E_SALVO",
      finalAction: "NUTRIR",
      reason: "Motivo sintético correlacionado",
    });
    await insertLead({
      batchId: "synthetic-crm-other-organization-batch",
      cnpj: "00000000000013",
      sourceRow: 13,
      testCaseId: "workflow-atual",
      processingResult: "CRM_DECIDIU_E_SALVO",
      finalAction: "NAO_ABORDAR",
      reason: "Motivo sintético de outra organização",
    });
    await insertLead({
      batchId: "synthetic-crm-uncorrelated-batch",
      cnpj: "00000000000014",
      sourceRow: 14,
      testCaseId: "workflow-atual",
      processingResult: "CRM_DECIDIU_E_SALVO",
      finalAction: "NAO_ABORDAR",
      reason: "Motivo sintético não correlacionado",
    });
    await insertLead({
      batchId: "synthetic-public-same-organization-batch",
      cnpj: "00000000000015",
      sourceRow: 15,
      testCaseId: "workflow-atual",
      processingResult: "INSERIDO_VALIDATION",
      reason: "Resultado público sintético",
    });
    await appPool?.query(
      `
        INSERT INTO prospecting_app.import_submissions (
          organization_id,
          producer_import_batch_id
        )
        VALUES
          ($1, 'synthetic-crm-same-organization-batch'),
          ($1, 'synthetic-public-same-organization-batch'),
          ('synthetic-organization-b', 'synthetic-crm-other-organization-batch')
      `,
      [demo3Actor.organizationId],
    );

    const visibility =
      await visibilityModule?.resolveLeadReadVisibility(demo3Actor);
    const result =
      await outsideAnalysisRepository?.listOutsideAnalysisCompanies(
        { page: 1, pageSize: 20 },
        visibility,
      );

    expect(
      result?.companies.map((company) => company.import_batch_id).sort(),
    ).toEqual([
      "synthetic-crm-production-batch",
      "synthetic-crm-same-organization-batch",
    ]);
    expect(result?.companies.map((company) => company.decisionReason).sort()).toEqual([
      "Motivo sintético correlacionado",
      "Motivo sintético de produção",
    ]);
    expect(result?.total).toBe(2);
  });
});
